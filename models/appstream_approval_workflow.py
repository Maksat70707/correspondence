# -*- coding: utf-8 -*-
from odoo import models


class AppstreamApprovalWorkflow(models.Model):
    """
    Порядок статусов маршрута должен определяться полем `sequence`, а не `id`.

    В appstream_approval у модели `appstream.approval.workflow` не задан
    `_order`, поэтому действует дефолтный `_order = 'id'`. Пока записи
    создавались один раз из XML в порядке файла, id и sequence совпадали и
    проблема не проявлялась. Как только статус пересоздали (удалили в
    интерфейсе, вернули обновлением модуля), его id уехал в конец таблицы —
    и сломались сразу два места, оба опирающиеся на дефолтную сортировку
    `search()`:

    1. `approval_mixin._approval_states()` собирает selection поля `state`
       как `[(r.state, r.name) for r in search(...)]` — без order. Статусы
       в статусбаре выстраиваются по id. Отсюда "Утверждение" и
       "Утверждение (мед. освидетельствование)" рисуются не между
       "Согласование" и "Обработка", а в самом конце маршрута — между
       "Ознакомление" и "Закрыто" (после статусов workflow идут только
       after-статусы: Закрыто / Отклонено / Отменено).

    2. `approval_workflow._next()` делает
       `search([... '|', ('sequence','>',s), '&', ('sequence','=',s),
       ('id','>',id)], limit=1)` — тоже без order. При limit=1 берётся
       запись с наименьшим **id** среди подходящих, а не с наименьшей
       sequence. Переход из "Согласование" уходит сразу в "Обработка" мимо
       "Утверждение", а `_action_approve` успевает записать
       `state = 'processing'` до выполнения before/after_script — из-за чего
       документу присваивался номер сразу после подписи начальника на
       Согласовании.

    Одна строка `_order` чинит оба места. Тай-брейк по id сохранён, чтобы
    домен `sequence = s AND id > id` в `_next()` оставался согласован с
    сортировкой.

    Правку имеет смысл передать в апстрим appstream_approval — баг
    фреймворочный и затрагивает все модули, которые на нём построены.
    """

    _inherit = "appstream.approval.workflow"
    _order = "sequence, id"
